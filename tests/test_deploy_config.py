"""
Checks on the deployment files, so a typo there fails CI instead of a deploy.

render.yaml: the free Render deployment. (Railway is configured in its dashboard, see README.)
"""

import shlex
from pathlib import Path

import yaml

from app.config import Settings

ROOT = Path(__file__).resolve().parents[1]


def render_service() -> dict:
    blueprint = yaml.safe_load((ROOT / "render.yaml").read_text(encoding="utf-8"))
    [service] = blueprint["services"]
    return service


def test_render_service_is_a_free_docker_web_service():
    service = render_service()
    assert service["type"] == "web"
    assert service["runtime"] == "docker"
    assert service["plan"] == "free"
    assert service["branch"] == "main"
    assert service["autoDeployTrigger"] == "checksPass"  # deploy only after CI passed


def test_render_health_check_exists_and_does_not_use_the_database(client):
    path = render_service()["healthCheckPath"]
    assert path == "/health/live"  # the check that never touches the database (see test_production.py)
    assert client.get(path, headers={"X-API-Key": ""}).status_code == 200


def test_render_start_command_runs_migrations_then_the_app():
    argv = shlex.split(render_service()["dockerCommand"])
    assert argv[:2] == ["sh", "-c"]
    script = argv[2]
    assert script.startswith("alembic upgrade head && exec uvicorn app.main:app")
    assert "--port ${PORT" in script  # Render tells the app its port


def test_render_env_vars_are_real_settings():
    env_vars = render_service()["envVars"]
    known = {name.upper() for name in Settings.model_fields}
    assert {v["key"] for v in env_vars} <= known
    by_key = {v["key"]: v for v in env_vars}
    assert by_key["ENVIRONMENT"]["value"] == "production"
    # Secrets are never written in the file: generated by Render or pasted in the dashboard.
    for key in ["API_KEY", "ADMIN_PASSWORD", "SESSION_SECRET", "DATABASE_URL", "VAPI_SECRET"]:
        assert "value" not in by_key[key], key
        assert by_key[key].get("generateValue") or by_key[key].get("sync") is False, key


def test_render_settings_would_pass_the_production_checks():
    """The values Render ends up with must satisfy ENVIRONMENT=production's startup checks."""
    values = {v["key"].lower(): v["value"] for v in render_service()["envVars"] if "value" in v}
    generated = "A" * 44  # Render generates base64 values of 256 bits = 44 characters
    Settings(
        _env_file=None,
        **values,
        api_key=generated,
        admin_password=generated,
        session_secret=generated,
        vapi_secret=generated,
        database_url="postgresql://user:pw@ep-example.eu-central-1.aws.neon.tech/neondb?sslmode=require",
    )
